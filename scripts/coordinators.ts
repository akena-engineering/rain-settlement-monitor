// Generates src/chain/coordinators.ts from Coordinator lists found via
// SupportedAssetAdded events (lists not included in this repo).
// Run once (pnpm coordinators) with the lists in ../../research/coordinators/;
// the output is committed as data.
import { readFileSync, writeFileSync } from "node:fs"
import { z } from "zod"
import { CHAINS } from "../src/data/snapshot"

// Coordinator 2.04 bytecode is 24,540 bytes; every older one is 18,181.
const V204_CODE_LEN = 24540

const Coord = z.object({
  address: z.string().regex(/^0x[0-9a-f]{40}$/),
  codeLen: z.number(),
  S: z.number(), // StatementPublished count, 30 days before 2026-11-10
})

// Excel-style labels: A…Z, AA, AB…
export function groupLabel(i: number): string {
  return i < 26
    ? String.fromCharCode(65 + i)
    : groupLabel(Math.floor(i / 26) - 1) + groupLabel(i % 26)
}

const config = Object.fromEntries(
  CHAINS.map((chain) => {
    const rows = z
      .array(Coord)
      .parse(
        JSON.parse(
          readFileSync(
            new URL(
              `../../research/coordinators/coords_${chain}.json`,
              import.meta.url,
            ),
            "utf8",
          ),
        ),
      )
      .sort((a, b) => b.S - a.S || a.address.localeCompare(b.address))
    return [
      chain,
      rows.map((c, i) => ({
        address: c.address,
        version: c.codeLen === V204_CODE_LEN ? "2.04" : "1",
        group: groupLabel(i),
      })),
    ]
  }),
)

const out = `// Generated by scripts/coordinators.ts from Coordinator lists found via
// SupportedAssetAdded events (lists not included in this repo).
// Groups are lettered by statement volume (30 days to 2026-11-10) per chain.
// Grouped by contract, without program names; mapping not attempted.
import type { Address } from "viem"
import type { CHAINS } from "../data/snapshot"

export type Chain = (typeof CHAINS)[number]
export type Coordinator = { address: Address; version: "1" | "2.04"; group: string }

export const COORDINATORS: Record<Chain, Coordinator[]> = ${JSON.stringify(config, null, 2)}
`
writeFileSync(new URL("../src/chain/coordinators.ts", import.meta.url), out)
